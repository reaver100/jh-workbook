// 라벨 -> {en, ko} 로 바꿔주기
function lookupWord(rawLabel) {
  const full = String(rawLabel || "").toLowerCase();
  const first = full.split(",")[0].trim();

  // 1) 사전에서 바로 찾기
  if (KO[first]) {
    return { en: EN_FIX[first] || first, ko: KO[first], exact: true };
  }
  // 2) 동의어들로도 찾아보기
  for (const syn of full.split(",").map(s => s.trim())) {
    if (KO[syn]) return { en: EN_FIX[syn] || syn, ko: KO[syn], exact: true };
  }
  // 3) 품종 같은 건 기본 단어로 묶기
  for (const g of GROUPS) {
    for (const m of g.match) {
      if (full.includes(m)) return { en: g.en, ko: g.ko, exact: true };
    }
  }
  // 4) 모르는 건 영어만
  return { en: EN_FIX[first] || first, ko: "", exact: false };
}
